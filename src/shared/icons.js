// How an icon is drawn: outline icons are stroked, logos are filled.
function shape(name) {
  if (SOLID[name]) return { ...SOLID[name], solid: true };
  return { viewBox: '0 0 24 24', body: P[name] || P.globe, solid: name === 'play' || name === 'pause' };
}

export function icon(name, size = 16, extra = '') {
  const { viewBox, body, solid } = shape(name);
  const paint = solid ? 'fill="currentColor" stroke="none"' : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  return `<svg class="ic ic-${name} ${extra}" width="${size}" height="${size}" viewBox="${viewBox}" ${paint} aria-hidden="true">${body}</svg>`;
}

export function hasIcon(name) {
  return Object.hasOwn(P, name) || Object.hasOwn(SOLID, name);
}

